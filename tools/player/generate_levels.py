"""Генерирует Go-каталог из data/player/levels.json; --check проверяет свежесть."""
import json
import re
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
levels = json.loads((ROOT / 'data/player/levels.json').read_text())
assert len(levels) == 15
assert [v['level'] for v in levels] == list(range(1,16))
assert levels[0]['xp'] == 0 and all(a['xp'] < b['xp'] for a,b in zip(levels,levels[1:]))
q = lambda value: json.dumps(value,ensure_ascii=False)
lines = ['// Code generated by tools/player/generate_levels.py; DO NOT EDIT.', 'package player', '', 'type LevelUnlock struct { Label string `json:"label"`; Status string `json:"status"` }', 'type LevelDefinition struct { Level int `json:"level"`; Title string `json:"title"`; XP int `json:"xp"`; Icon string `json:"icon"`; Unlocks []LevelUnlock `json:"unlocks"` }', '', 'var LevelCatalog = []LevelDefinition{']
for v in levels:
    items = ','.join('{'+q(u['label'])+','+q(u['status'])+'}' for u in v['unlocks'])
    lines.append(' {'+str(v['level'])+','+q(v['title'])+','+str(v['xp'])+','+q(v['icon'])+',[]LevelUnlock{'+items+'}},')
lines += ['}', '', 'var levelThresholds = func() []int {', ' values := make([]int,len(LevelCatalog))', ' for i,v := range LevelCatalog { values[i]=v.XP }; return values', '}()', '']
output = '\n'.join(lines)
path = ROOT / 'backend/internal/domain/player/levels.generated.go'
if '--check' in sys.argv:
    tokens = lambda value: re.findall(r'`[^`]*`|"(?:\\.|[^"\\])*"|[A-Za-z_0-9]+|[^\s,;]', value)
    if not path.exists() or tokens(path.read_text())!=tokens(output): raise SystemExit('Каталог уровней Go устарел; запустите tools/player/generate_levels.py')
else: path.write_text(output)
