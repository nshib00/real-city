"""Генерирует клиентский каталог и встроенные данные backend из data/buildings/catalog-v2.json."""

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "data/buildings/catalog-v2.json"
TYPESCRIPT = ROOT / "shared/catalog/buildings.ts"
GO_COPY = ROOT / "backend/internal/domain/catalog/buildings.v2.json"


def main():
    raw = SOURCE.read_text(encoding="utf-8")
    data = json.loads(raw)
    if data.get("schema_version") != 1 or data.get("balance_version") != 2:
        raise SystemExit("неподдерживаемая версия каталога")
    buildings = data["buildings"]
    ids = [item["type"] for item in buildings]
    if len(ids) != len(set(ids)):
        raise SystemExit("повтор building_id")
    for item in buildings:
        if not item.get("name") or item["footprint"]["width"] < 1 or item["footprint"]["height"] < 1 or item.get("health", 0) <= 0:
            raise SystemExit(f"неверная запись {item.get('type')}")
        for level in item.get("upgradeLevels") or [item]:
            if level["buildSeconds"] < 0 or level["population"] < 0 or level.get("health", 0) <= 0:
                raise SystemExit(f"неверные параметры {item['type']} L{level['level']}")
            if any(cost["amount"] < 0 for cost in level["cost"]):
                raise SystemExit(f"отрицательная стоимость {item['type']} L{level['level']}")
    GO_COPY.write_text(raw, encoding="utf-8")
    union = "\n".join(f"  | '{name}'" for name in ids)
    TYPESCRIPT.write_text(
        "// Code generated by tools/buildings/generate_catalog.py; DO NOT EDIT.\n"
        "import catalogData from '../../data/buildings/catalog-v2.json'\n\n"
        "export type BuildingTypeId =\n  | `ruins_${string}`\n" + union + "\n\n"
        "export type BuildingCatalogItem = {\n"
        "  type: BuildingTypeId\n"
        "  category: 'housing' | 'fields' | 'industry' | 'defense' | 'roads' | 'storage' | 'social' | 'trade' | 'center'\n"
        "  name: string\n  level: number\n  footprint: { width: number; height: number }\n"
        "  buildSeconds: number\n  population: number\n  health: number\n"
        "  cost: { resource: string; amount: number }[]\n  firstLevel: boolean\n"
        "  upgradeTo: BuildingTypeId[]\n"
        "  upgradeLevels?: { level: number; buildSeconds: number; population: number; health: number; cost: { resource: string; amount: number }[]; nextType?: BuildingTypeId }[]\n"
        "}\n\n"
        "export const buildingCatalog: BuildingCatalogItem[] = catalogData.buildings as unknown as BuildingCatalogItem[]\n",
        encoding="utf-8",
    )
    print(f"сгенерированы TS и Go JSON из data: {len(ids)} ID")


if __name__ == "__main__":
    main()
