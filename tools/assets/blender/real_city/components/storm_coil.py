"""Six industrial storm coils, with readable operating and failure states."""

from __future__ import annotations

import math

from .. import geometry as g
from .common import mat


def _ring(c, name, radius, z, material, *, segments=12, width=0.075):
    verts = []
    faces = []
    for i in range(segments):
        a = math.tau * i / segments
        b = math.tau * (i + 1) / segments
        p = (radius * math.cos(a), radius * math.sin(a))
        q = (radius * math.cos(b), radius * math.sin(b))
        length = math.hypot(q[0] - p[0], q[1] - p[1])
        nx, ny = -(q[1] - p[1]) / length, (q[0] - p[0]) / length
        base = len(verts)
        for x, y in (p, q):
            for side, dz in ((-1, -1), (1, -1), (1, 1), (-1, 1)):
                verts.append((x + nx * side * width / 2,
                              y + ny * side * width / 2, z + dz * width / 2))
        faces.extend(tuple(base + j for j in face) for face in
                     ((0, 1, 2, 3), (4, 7, 6, 5), (0, 4, 5, 1),
                      (1, 5, 6, 2), (2, 6, 7, 3), (3, 7, 4, 0)))
    g.mesh(name, c, verts, faces, material)


def _scrap(c, copper, steel, concrete, *, ruined):
    for i in range(5 if ruined else 3):
        x = -0.95 + 0.38 * i
        g.box(f"fallen_winding_{i}", c, (x, 0.66 - 0.12 * i, 0.17),
              (0.30, 0.11, 0.09), copper, bevel=0.018, rotation=(0, 0, 0.15 * i))
        g.box(f"fallen_frame_{i}", c, (x, 0.48 - 0.1 * i, 0.15),
              (0.25, 0.09, 0.07), steel, bevel=0.014)
    if ruined:
        for i in range(3):
            g.box(f"broken_plinth_{i}", c, (-0.48 + 0.48 * i, -0.35, 0.17),
                  (0.36, 0.29, 0.12), concrete, bevel=0.025,
                  rotation=(0, 0, 0.16 * (i - 1)))


def add_storm_coil(c, mats: dict, *, level: int, state: str) -> None:
    if level not in range(1, 7):
        raise ValueError(f"Unsupported storm coil level: {level}")
    if state not in {"construction", "active", "no_fuel", "no_crew", "damaged", "ruined"}:
        raise ValueError(f"Unsupported storm coil state: {state}")
    copper = mat(mats, "copper")
    dark = mat(mats, "dark_metal")
    steel = mat(mats, "steel_light")
    stone = mat(mats, "stone_block")
    concrete = mat(mats, "reinforced_concrete") if level >= 3 else stone
    armor = mat(mats, "armor")
    cyan = mat(mats, "glass_cyan")
    insulator = mat(mats, "whitewash")
    char = mat(mats, "damage_char")
    building = state == "construction"
    damaged = state == "damaged"
    ruined = state == "ruined"
    height = 1.28 + 0.10 * level

    # The shared ground is generated by the orchestrator and remains identical.
    for x in (-0.56, 0.56):
        for y in (-0.55, 0.55):
            g.box(f"foundation_foot_{x}_{y}", c, (x, y, 0.19),
                  (0.42, 0.42, 0.17), concrete, bevel=0.033)
    for x in (-0.51, 0.51):
        g.box(f"foundation_sill_{x}", c, (x, 0, 0.27),
              (0.22, 1.21, 0.15), concrete, bevel=0.022)
    for y in (-0.50, 0.50):
        g.box(f"foundation_sill_y_{y}", c, (0, y, 0.27),
              (1.13, 0.20, 0.15), concrete, bevel=0.022)
    g.cylinder("turntable", c, (0, 0, 0.34), 0.42, 0.15, dark, vertices=20)
    g.cylinder("copper_bearing", c, (0, 0, 0.43), 0.33, 0.07, copper, vertices=20)

    if ruined:
        g.cylinder("broken_core_stump", c, (0, 0, 0.60), 0.25, 0.36, dark, vertices=16)
        g.beam("collapsed_upper_core", c, (-0.84, -0.17, 0.18),
               (-0.15, -0.28, 0.24), 0.20, dark)
        _scrap(c, copper, steel, concrete, ruined=True)
        if level >= 2:
            for i, x in enumerate((-0.76, 0.76)):
                g.cylinder(f"fallen_insulator_{i}", c, (x, -0.34, 0.18),
                           0.17, 0.15, insulator, vertices=12)
        if level >= 3:
            _ring(c, "collapsed_secondary_winding", 0.43, 0.17, copper)
        if level >= 4:
            for i, x in enumerate((-0.91, 0.91)):
                g.box(f"fallen_guard_rail_{i}", c, (x, 0.35, 0.17),
                      (0.11, 0.70, 0.09), armor, bevel=0.015)
        if level >= 5:
            _ring(c, "fallen_discharge_ring", 0.64, 0.23, copper,
                  segments=16, width=0.10)
        if level >= 6:
            g.cylinder("fallen_multilayer_collar", c, (0.86, 0.32, 0.22),
                       0.30, 0.15, steel, vertices=16)
        return

    # Steel core is rooted in its turntable; construction and damage cut it down.
    core_top = 0.89 if building else 1.10 if damaged else height
    g.cylinder("steel_core", c, (0, 0, (0.44 + core_top) / 2),
               0.21 if level < 6 else 0.26, core_top - 0.44, dark, vertices=16)
    g.cylinder("lower_core_collar", c, (0, 0, 0.59), 0.30, 0.10, steel, vertices=20)
    if level >= 6 and not (building or damaged):
        for radius, z in ((0.34, 0.80), (0.39, 1.15)):
            _ring(c, f"multi_layer_core_{z}", radius, z, steel, width=0.085)

    # A winding is a stack of horizontal copper bands around the industrial column.
    rows = 2 if building else 4 if damaged else 7 + level
    max_z = min(core_top - 0.13, 1.05 + level * 0.07)
    for i in range(rows):
        z = 0.65 + (max_z - 0.65) * i / max(1, rows - 1)
        _ring(c, f"primary_winding_{i}", 0.28 if level < 6 else 0.33, z, copper,
              segments=12, width=0.055)
    if level >= 3 and not (building or damaged):
        for i in range(4 + level):
            z = 0.77 + i * 0.09
            _ring(c, f"secondary_winding_{i}", 0.40, z, copper,
                  segments=12, width=0.045)

    if building:
        g.cylinder("unmounted_insulator", c, (0.81, -0.55, 0.20), 0.14, 0.13,
                   insulator, vertices=12)
        g.box("loose_copper_bus", c, (-0.84, -0.55, 0.16), (0.65, 0.10, 0.10),
              copper, bevel=0.015, rotation=(0, 0, -0.19))
        g.box("loose_steel_brace", c, (0.70, 0.62, 0.16), (0.62, 0.10, 0.10),
              steel, bevel=0.015, rotation=(0, 0, 0.25))
        if level >= 2:
            for i, x in enumerate((-0.81, 0.81)):
                g.cylinder(f"unmounted_insulator_extra_{i}", c, (x, 0.32, 0.20),
                           0.14, 0.13, insulator, vertices=12)
        if level >= 3:
            _ring(c, "partly_installed_second_winding", 0.39, 0.70, copper)
        if level >= 4:
            g.beam("unraised_guard_segment", c, (0.75, 0.73, 0.18),
                   (1.14, 0.61, 0.23), 0.09, armor)
        if level >= 5:
            _ring(c, "unmounted_discharge_ring", 0.53, 0.18, copper,
                  segments=16, width=0.09)
        if level >= 6:
            g.cylinder("unmounted_multilayer_collar", c, (-0.78, 0.70, 0.21),
                       0.28, 0.14, steel, vertices=16)
        return

    # Four supported side terminals make the mechanism readable without a Tesla-tower silhouette.
    for i, (x, y) in enumerate(((0.68, 0), (-0.68, 0), (0, 0.68), (0, -0.68))):
        if damaged and i in (0, 2):
            continue
        g.box(f"terminal_foot_{i}", c, (x, y, 0.35), (0.25, 0.25, 0.14),
              steel, bevel=0.023)
        g.cylinder(f"terminal_post_{i}", c, (x, y, 0.68), 0.07, 0.58,
                   steel, vertices=12)
        g.cylinder(f"terminal_insulator_{i}", c, (x, y, 0.95), 0.16, 0.16,
                   insulator, vertices=12)
        g.cylinder(f"terminal_copper_cap_{i}", c, (x, y, 1.05), 0.13, 0.06,
                   copper, vertices=12)
        if level >= 2:
            g.cylinder(f"terminal_lower_insulator_{i}", c, (x, y, 0.78), 0.12,
                       0.08, insulator, vertices=12)
            g.beam(f"terminal_brace_{i}", c, (x, y, 0.54),
                   (x * 0.55, y * 0.55, 0.55), 0.065, steel)

    if damaged:
        g.beam("broken_core_tip", c, (0.76, 0.48, 0.18),
               (1.08, 0.69, 0.24), 0.17, char)
        _scrap(c, copper, steel, concrete, ruined=False)
        if level >= 3:
            _ring(c, "surviving_second_winding", 0.39, 0.82, copper)
        if level >= 4:
            for x in (-0.67, 0.67):
                g.beam(f"bent_guard_{x}", c, (x, 0.67, 0.30),
                       (x * 0.83, 0.70, 0.84), 0.065, armor)
        if level >= 5:
            _ring(c, "broken_discharge_ring_on_ground", 0.57, 0.18,
                  copper, segments=16, width=0.09)
        if level >= 6:
            g.cylinder("damaged_multilayer_collar", c, (0, 0, 1.02),
                       0.36, 0.11, steel, vertices=16)
        return

    g.cylinder("top_emitter_socket", c, (0, 0, height + 0.04),
               0.34, 0.12, steel, vertices=20)
    g.cylinder("emitter_lens", c, (0, 0, height + 0.12),
               0.19, 0.08, cyan if state == "active" else dark, vertices=20)
    for z in (0.72, height + 0.03):
        _ring(c, f"concentric_emitter_{z}", 0.45 if z > 1 else 0.35,
              z, copper, segments=16, width=0.07)

    if level >= 4:
        for i, (x, y) in enumerate(((0.67, 0.67), (-0.67, 0.67),
                                     (-0.67, -0.67), (0.67, -0.67))):
            g.beam(f"guard_vertical_{i}", c, (x, y, 0.30),
                   (x, y, 1.12), 0.055, armor)
        for z in (0.48, 1.08):
            _ring(c, f"protective_grille_{z}", 0.91, z, armor,
                  segments=16, width=0.047)
    if level >= 5:
        _ring(c, "discharge_ring", 0.58, height + 0.20, copper,
              segments=16, width=0.10)
        for i in range(4):
            a = math.tau * i / 4
            x, y = math.cos(a), math.sin(a)
            g.beam(f"discharge_spoke_{i}", c,
                   (0.27 * x, 0.27 * y, height + 0.07),
                   (0.58 * x, 0.58 * y, height + 0.20), 0.065, steel)

    # Service states keep the complete machine, with a distinct readable indicator.
    indicator = cyan if state == "active" else char if state == "no_fuel" else insulator
    g.box("service_indicator_housing", c, (0, -0.77, 0.46),
          (0.30, 0.11, 0.25), dark, bevel=0.027)
    g.box(f"service_indicator_{state}", c, (0, -0.834, 0.46),
          (0.17, 0.026, 0.12), indicator, bevel=0.005)
    if state == "no_fuel":
        g.cylinder("empty_fuel_gauge", c, (0.40, -0.72, 0.52),
                   0.17, 0.08, char, vertices=12, rotation=(math.pi / 2, 0, 0))
        g.box("empty_fuel_body", c, (0.42, -0.79, 0.25),
              (0.29, 0.27, 0.30), copper, bevel=0.035)
    if state == "no_crew":
        g.box("operator_panel_stand", c, (-0.79, -0.48, 0.29),
              (0.09, 0.10, 0.38), dark, bevel=0.012)
        g.box("vacant_operator_panel", c, (-0.79, -0.48, 0.48),
              (0.32, 0.13, 0.35), insulator, bevel=0.025)
        g.beam("operator_lever_parked", c, (-0.79, -0.48, 0.63),
               (-0.79, -0.32, 0.82), 0.055, dark)
