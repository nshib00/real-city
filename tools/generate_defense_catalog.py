#!/usr/bin/env python3
"""Generate defense building catalog values from the approved Markdown specifications."""

from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
DEFENSE = ROOT / "docs/buildings/defense"
SPECS = [
    ("stakes", "defense_stakes", "TypeDefenseStakes", "Колья"),
    ("resin-snare", "defense_resin_snare", "TypeDefenseResinSnare", "Смоляная западня"),
    ("bolt-thrower", "defense_bolt_thrower", "TypeDefenseBoltThrower", "Болтомёт"),
    ("storm-coil", "defense_storm_coil", "TypeDefenseStormCoil", "Грозовая катушка"),
    ("automaton-bay", "defense_automaton_bay", "TypeDefenseAutomatonBay", "Мастерская автоматонов"),
    ("guardian-enclosure", "defense_guardian_enclosure", "TypeDefenseGuardianEnclosure", "Вольер союзников"),
]
RESOURCES = {
    "монет": "coins", "древесины": "wood", "досок": "planks", "веревки": "rope",
    "каменных блоков": "stone_block", "железных слитков": "iron_ingot",
    "смолы": "resin", "стали": "steel", "механизмов": "mechanism",
    "защитных пластин": "armor_plates", "медных деталей": "copper_parts",
    "электроники": "electronics", "железобетона": "reinforced_concrete",
    "усиленных балок": "reinforced_beams", "супер-механизма": "super_mechanism",
    "премиум-досок": "premium_planks", "трав": "herbs",
    "сердцевины древня": "elderwood-heart", "светокристалла": "light_crystal",
    "доски": "planks", "железных слитка": "iron_ingot", "каменных блока": "stone_block",
    "механизма": "mechanism", "защитные пластины": "armor_plates",
    "сердцевин древня": "elderwood-heart", "веревок": "rope",
}


def rows(file: Path):
    result = []
    for line in file.read_text().splitlines():
        if not re.match(r"^\|\s*\d+\s*\|", line):
            continue
        cols = [value.strip() for value in line.strip("| ").split("|")]
        level = int(cols[0])
        cost = []
        for part in cols[1].split(", "):
            match = re.fullmatch(r"(\d+) (.+)", part)
            if not match or match[2] not in RESOURCES:
                raise ValueError(f"Unknown defense cost in {file}: {part}")
            cost.append((RESOURCES[match[2]], int(match[1])))
        time_match = re.fullmatch(r"(\d+) мин", cols[2])
        if not time_match:
            raise ValueError(f"Unknown defense duration in {file}: {cols[2]}")
        result.append(dict(level=level, cost=cost, seconds=int(time_match[1]) * 60,
                           builders=int(cols[3]), health=int(cols[-2]), columns=cols))
    if not result or [r["level"] for r in result] != list(range(1, len(result) + 1)):
        raise ValueError(f"Missing defense levels in {file}")
    return result


def go_cost(cost):
    return "[]building.Cost{" + ", ".join(f'{{Resource: "{key}", Amount: {amount}}}' for key, amount in cost) + "}"


def ts_cost(cost):
    return "[" + ", ".join(f"{{ resource: '{key}', amount: {amount} }}" for key, amount in cost) + "]"


def main():
    go_lines = ["// Code generated by tools/generate_defense_catalog.py; DO NOT EDIT.", "package catalog", "",
                'import ("time"; "real-city/backend/internal/domain/building")', "", "func init() {", "  for kind, spec := range defenseBuildings { Buildings[kind] = spec }", "}",
                "", "var defenseBuildings = map[building.Type]BuildingType{"]
    ts_lines = ["// Code generated by tools/generate_defense_catalog.py; DO NOT EDIT.",
                "import type { BuildingCatalogItem } from './buildings'", "",
                "export const defenseSpecBuildings: BuildingCatalogItem[] = ["]
    for filename, kind, go_type, name in SPECS:
        levels = rows(DEFENSE / f"{filename}.md")
        first = levels[0]
        go_lines += [f"  building.{go_type}: {{Type: building.{go_type}, Category: \"defense\", Name: \"{name}\", Level: 1,",
                     f"    Footprint: building.Footprint{{Width: 1, Height: 1}}, BuildDuration: {first['seconds']} * time.Second, Population: {first['builders']}, Health: {first['health']},",
                     f"    RequiresTownHall: true, CountsTowardLimit: {str(kind not in ('defense_stakes', 'defense_resin_snare')).lower()}, Cost: {go_cost(first['cost'])},",
                     "    UpgradeLevels: []BuildingUpgradeLevel{"]
        ts_lines += [f"  {{ type: '{kind}', category: 'defense', name: '{name}', level: 1, footprint: {{ width: 1, height: 1 }},",
                     f"    buildSeconds: {first['seconds']}, population: {first['builders']}, health: {first['health']}, cost: {ts_cost(first['cost'])}, firstLevel: true, upgradeTo: [],",
                     "    upgradeLevels: ["]
        for level in levels:
            go_lines.append(f"      {{Level: {level['level']}, BuildDuration: {level['seconds']} * time.Second, Population: {level['builders']}, Health: {level['health']}, Cost: {go_cost(level['cost'])}}},")
            ts_lines.append(f"      {{ level: {level['level']}, buildSeconds: {level['seconds']}, population: {level['builders']}, health: {level['health']}, cost: {ts_cost(level['cost'])} }},")
        go_lines += ["    },", "  },"]
        ts_lines += ["    ],", "  },"]
    go_lines += ["}", ""]
    ts_lines += ["]", ""]
    go_output = ROOT / "backend/internal/domain/catalog/defense_generated.go"
    go_output.write_text("\n".join(go_lines))
    subprocess.run(["gofmt", "-w", str(go_output)], check=True)
    (ROOT / "shared/catalog/defenseSpecs.generated.ts").write_text("\n".join(ts_lines))


if __name__ == "__main__":
    main()
