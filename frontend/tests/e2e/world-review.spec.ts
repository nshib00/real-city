import { expect, test } from 'playwright/test'
import { mockInterfaceWorld } from './ui-fixture'

test('свой и чужой объект, контур размещения и offline на настоящем canvas', async ({ page, context }, info) => {
  test.skip(!['1440-dpr1', '390-dpr2'].includes(info.project.name), 'Представительные desktop/mobile; геометрия HUD проверяется во всей матрице.')
  const { errors, unknown, actions } = await mockInterfaceWorld(page, { objects: true })
  await page.goto('/')
  await expect(page.locator('.pixi-stage canvas')).toBeVisible()
  await expect(page.getByLabel('Постройки: 2/8', { exact: true })).toBeVisible()
  const coordinates = page.locator('.map-coordinate-selection')
  const inspect = async (x: number, y: number) => {
    if (!await coordinates.getAttribute('open').then(value => value !== null)) { await coordinates.locator('summary').focus(); await page.keyboard.press('Space') }
    await coordinates.getByLabel('X', { exact: true }).fill(String(x))
    await coordinates.getByLabel('Y', { exact: true }).fill(String(y))
    await coordinates.getByRole('button', { name: 'Осмотреть клетку' }).focus()
    await page.keyboard.press('Enter')
    await coordinates.locator('summary').focus()
    await page.keyboard.press('Space')
    const expand = page.getByRole('button', { name: 'Развернуть инспектор' })
    if (await expand.isVisible()) await expand.click()
  }
  await inspect(4, 4)
  const inspector = page.getByLabel('Инспектор', { exact: true })
  await expect(inspector).toContainText('Ваша постройка')
  await expect(inspector.getByRole('heading', { name: 'Землянка', exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('own-building.png') })
  await inspect(8, 4)
  await expect(inspector).toContainText('Чужая постройка')
  await expect(inspector).toContainText('Соседний город')
  await page.screenshot({ path: info.outputPath('foreign-building.png') })
  await inspect(9, 3)
  await page.getByRole('button', { name: 'Строить', exact: true }).click()
  await page.getByRole('button', { name: 'Предпросмотр Землянка на карте', exact: true }).click()
  await expect(page.locator('.placement-footprint')).toBeVisible()
  expect((await page.locator('.build-menu-collapsed').boundingBox())!.height).toBeLessThan(144)
  if (info.project.name === '390-dpr2') await expect(page.getByRole('button', { name: 'Развернуть инспектор' })).toHaveAttribute('aria-expanded', 'false')
  await page.screenshot({ path: info.outputPath('placement.png') })
  await page.keyboard.press('Escape')
  await expect(page.locator('.placement-footprint')).toHaveCount(0)
  await inspect(5, 4)
  await page.getByRole('button', { name: 'Строить', exact: true }).click()
  await page.getByRole('button', { name: 'Предпросмотр Землянка на карте', exact: true }).click()
  await expect(page.locator('.map-placement-preview-invalid')).toBeVisible()
  expect(await page.locator('.placement-footprint').evaluate(node => getComputedStyle(node).strokeDasharray)).not.toBe('none')
  await page.screenshot({ path: info.outputPath('placement-invalid.png') })
  await page.keyboard.press('Escape')
  await context.setOffline(true)
  await expect(page.getByText('Нет связи — подтверждение сервера недоступно', { exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('offline.png') })
  await context.setOffline(false)
  expect(errors).toEqual([])
  expect([...new Set(unknown)]).toEqual([])
  expect(actions).toEqual([])
})

test('touch-перемещение не выбирает клетку и не отправляет действие', async ({ page, context }, info) => {
  test.skip(info.project.name !== '390-dpr2', 'Touch проверяется в мобильном проекте.')
  const { errors, unknown } = await mockInterfaceWorld(page)
  await page.goto('/')
  await expect(page.locator('.pixi-stage canvas')).toBeVisible()
  const map = page.locator('.map-origin')
  const before = await map.getAttribute('style')
  const session = await context.newCDPSession(page)
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 100, y: 360, id: 1 }] })
  await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 140, y: 400, id: 1 }] })
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect.poll(() => map.getAttribute('style')).not.toBe(before)
  await expect(page.locator('#game-inspector > h2')).toHaveText('Карта мира')
  expect(await page.locator('.pixi-stage').evaluate(node => getComputedStyle(node).touchAction)).toBe('pinch-zoom')
  const scaleBefore = await map.getAttribute('style')
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 100, y: 360, id: 1 }, { x: 200, y: 360, id: 2 }] })
  await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 80, y: 360, id: 1 }, { x: 220, y: 360, id: 2 }] })
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  expect(await map.getAttribute('style')).toBe(scaleBefore)
  await page.screenshot({ path: info.outputPath('touch-map.png') })
  expect(errors).toEqual([])
  expect(unknown).toEqual([])
})
