import { expect, test } from 'playwright/test'

test('макет: цикл строительства, отмена, снимок и отсутствие горизонтальной прокрутки', async ({ page }, info) => {
  await page.goto('/design.html')
  const prototype = page.getByRole('region', { name: 'Интерактивный макет Эолии' })
  await prototype.getByRole('button', { name: 'Тайл 1, 1', exact: true }).click()
  await prototype.getByRole('button', { name: 'Открыть строительство' }).click()
  await prototype.getByLabel('Нехватка ресурсов').check()
  await expect(prototype.getByRole('button', { name: 'Предпросмотр размещения' })).toBeDisabled()
  await prototype.getByLabel('Нехватка ресурсов').uncheck()
  await prototype.getByRole('button', { name: 'Предпросмотр размещения' }).click()
  await prototype.getByRole('button', { name: 'Разместить в макете' }).click()
  await prototype.getByRole('button', { name: 'Открыть объект' }).click()
  await expect(prototype.getByText(/Объект открыт/)).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(prototype.getByRole('button', { name: 'Тайл 1, 1: стройка' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(prototype.getByText(/Объект открыт/)).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Землянка', exact: true })).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.screenshot({ path: info.outputPath('prototype-edge.png'), fullPage: true })
  await prototype.getByLabel('Компоновка').selectOption('desk')
  await page.screenshot({ path: info.outputPath('prototype-desk.png'), fullPage: true })
})
